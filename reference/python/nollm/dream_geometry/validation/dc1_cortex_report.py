def build_report() -> str:
    with tempfile.TemporaryDirectory(prefix="dc1-report-") as directory:
        results = _run_fixtures(Path(directory))
    lines = [
        "# DC1 Cortex Compiler Baseline Report",
        "",
        "Generated by `python -m nollm.dream_geometry.validation.dc1_cortex_report`.",
        "",
        "## Execution",
        "",
        f"- Python: `{platform.python_version()}`",
        "- contract_version: `dc1.v1`",
        "- fixture_data: `synthetic_only`",
        "- third_party_dependencies: `none`",
        "",
        "## Fixture Results",
        "",
        "| fixture | result |",
        "|---|---|",
    ]
    for name, result in results:
        lines.append(f"| {name} | {result} |")
    lines.extend(
        [
            "",
            "## Known Limits",
            "",
            "- DC1 does not prove natural-language understanding, rule truth, rule authority, Geometry placement, Field propagation, Recall quality, runtime integration, or security authenticity.",
            "- Growth budget schema is `max_axes`, `max_total_steps`, `max_ray_steps` with hard caps `8/48/16`.",
            "- Query budget schema is `max_axes`, `max_charts`, `max_layers`, `max_cells_per_layer` with hard caps `8/64/64/256`.",
            "- Relative-time Query requires at least one exact `explicit_in_query` text span and preserves caller text without absolute-time resolution.",
            "- `possible_conflict_refs` are checked only as explicit DE1 DreamShard or InterpretationRecord pointers; DC1 performs no conflict judgment.",
            "- Reopen validates compiled proposal semantics and receipt input snapshot / submitted fingerprint / normalized proposal consistency.",
            "- Same `rule_id` must keep one `(rule_version, rule_label, source_ref)` identity within a proposal.",
            "- Fingerprints are deterministic equivalence keys for idempotency and report recomputation only.",
        ]
    )
    return "\n".join(lines) + "\n"


def write_report(output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build_report(), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the DC1 Cortex Compiler baseline report.")
    parser.add_argument("--output", required=True)
    args = parser.parse_args(argv)
    write_report(Path(args.output))
    return 0


def _run_fixtures(root: Path) -> tuple[tuple[str, str], ...]:
    evidence = _fixture_store(root / "evidence")
    cortex = open_cortex_store(root / "cortex", evidence)
    accepted = cortex.compile_growth(_growth_payload()).proposal.proposal_id == "gp_kunming_growth_v1"
    retry = cortex.compile_growth(_growth_payload()).idempotent
    query_before = _tree_digest(root / "cortex")
    query = compile_query(_query_payload())
    query_zero_persistence = query.ephemeral and _tree_digest(root / "cortex") == query_before
    mismatch = _raises_code(lambda: cortex.compile_growth(_bad_explicit_payload()), "DC1_INVALID_TEXT_SPAN")
    memory_query = _raises_code(lambda: compile_query(_bad_query_memory_basis()), "DC1_QUERY_MEMORY_BASIS_FORBIDDEN")
    reopened = open_cortex_store(root / "cortex", evidence).get_growth_proposal("gp_kunming_growth_v1").subject_shard_id == "shard:rain"
    return (
        ("synthetic DreamShard fixture", "pass"),
        ("growth accepted with basis refs", "pass" if accepted else "fail"),
        ("growth idempotent retry", "pass" if retry else "fail"),
        ("query ephemeral zero persistence", "pass" if query_zero_persistence else "fail"),
        ("explicit span mismatch rejected", "pass" if mismatch else "fail"),
        ("query memory basis rejected", "pass" if memory_query else "fail"),
        ("cortex reopen validates proposal receipt", "pass" if reopened else "fail"),
        ("sealed path diff summary", "not run by report; covered by delivery validation"),
    )


def _fixture_store(root: Path):
    store = open_evidence_store(root)
    store.put_dream_shard(_shard("shard:rain", "昆明于2026年6月29日下雨了。"))
    store.put_dream_shard(_shard("shard:city", "昆明是中国云南省的城市。"))
    store.put_dream_shard(_shard("shard:revision", "2026年6月29日的天气记录仅适用于该日。"))
    store.put_interpretation(
        InterpretationRecord(
            "interpretation:city-note",
            "shard:city",
            InterpretationKind.classification,
            "城市 classification note",
            InterpretationAuthoringMode.llm_proposed,
            (),
            (),
            UsageState.tentative,
        )
    )
    return store


