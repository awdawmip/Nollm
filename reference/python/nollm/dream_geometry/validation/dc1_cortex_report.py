def _bad_query_memory_basis() -> dict:
    payload = _query_payload()
    payload["axes"][0]["ray"][0]["basis"] = "explicit_in_shard"
    return payload


def _tree_digest(root: Path) -> tuple[tuple[str, str], ...]:
    if not root.exists():
        return ()
    return tuple(sorted((str(path.relative_to(root)), path.read_text(encoding="utf-8")) for path in root.rglob("*") if path.is_file()))


def _raises_code(callback, code: str) -> bool:
    try:
        callback()
    except DC1Rejection as exc:
        return code in exc.reason_codes
    return False


